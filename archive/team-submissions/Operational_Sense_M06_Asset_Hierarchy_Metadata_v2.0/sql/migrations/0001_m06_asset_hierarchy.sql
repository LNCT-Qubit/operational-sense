-- Operational Sense M06 — minimum PostgreSQL implementation candidate.
-- Prerequisites: approved M05/Common Data Model review; see README before applying.
-- This migration deliberately fails if core target tables already exist. Do not
-- bypass that guard: reconcile with the real M05 schema instead of duplicating it.
-- Run on a disposable development database with psql --single-transaction.

DO $m06_preflight$
BEGIN
    IF to_regclass('public.equipment_class') IS NOT NULL THEN
        RAISE EXCEPTION 'M06 preflight: public.equipment_class already exists; reconcile with M05 instead of creating a competing table';
    END IF;
    IF to_regclass('public.asset_node') IS NOT NULL THEN
        RAISE EXCEPTION 'M06 preflight: public.asset_node already exists; reconcile with M05 instead of creating a competing table';
    END IF;
    IF to_regclass('public.m06_equipment_component_reference') IS NOT NULL THEN
        RAISE EXCEPTION 'M06 preflight: public.m06_equipment_component_reference already exists; inspect prior state before continuing';
    END IF;
END
$m06_preflight$;

CREATE TABLE public.equipment_class (
    equipment_class_id VARCHAR(32) PRIMARY KEY,
    class_name TEXT NOT NULL CHECK (btrim(class_name) <> ''),
    description TEXT NOT NULL CHECK (btrim(description) <> ''),
    review_status TEXT NOT NULL DEFAULT 'PENDING_REVIEW'
        CHECK (btrim(review_status) <> ''),
    source_sheet TEXT NOT NULL DEFAULT 'Equipment_Reference',
    source_row_number INTEGER NOT NULL CHECK (source_row_number > 1)
);

COMMENT ON TABLE public.equipment_class IS
    'Source-backed equipment class reference. Seed rows remain PENDING_REVIEW until domain approval.';
COMMENT ON COLUMN public.equipment_class.review_status IS
    'Free-text review state pending Common Data Model approval; no approval is inferred by this migration.';

CREATE TABLE public.asset_node (
    asset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_asset_id BIGINT NULL,
    asset_level TEXT NOT NULL CHECK (btrim(asset_level) <> ''),
    asset_name TEXT NOT NULL CHECK (btrim(asset_name) <> ''),
    equipment_class_id VARCHAR(32) NULL,
    model_label TEXT NULL,
    model_is_illustrative BOOLEAN NOT NULL DEFAULT FALSE,
    site_identifier TEXT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING_REVIEW' CHECK (btrim(status) <> ''),
    CONSTRAINT fk_asset_node_parent
        FOREIGN KEY (parent_asset_id)
        REFERENCES public.asset_node (asset_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_asset_node_equipment_class
        FOREIGN KEY (equipment_class_id)
        REFERENCES public.equipment_class (equipment_class_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_asset_node_not_self_parent
        CHECK (parent_asset_id IS NULL OR parent_asset_id <> asset_id)
);

CREATE INDEX ix_asset_node_parent_asset_id
    ON public.asset_node (parent_asset_id);
CREATE INDEX ix_asset_node_equipment_class_id
    ON public.asset_node (equipment_class_id);

COMMENT ON TABLE public.asset_node IS
    'Provisional arbitrary-depth asset hierarchy based on M04 ASSET_NODE logical fields. Hierarchy vocabulary and identifier strategy require approval.';
COMMENT ON COLUMN public.asset_node.asset_level IS
    'Not constrained to Plant/Area/System/Equipment/Component until Group 1 approves hierarchy levels and Subsystem treatment.';
COMMENT ON COLUMN public.asset_node.model_label IS
    'Descriptive model label only; not a separate approved EquipmentModel entity.';
COMMENT ON COLUMN public.asset_node.model_is_illustrative IS
    'True when the label is illustrative and must not be treated as a verified physical model.';

-- Source-provenance mapping only. This table does not declare subsystem or
-- component labels to be approved hierarchy nodes or approved failure taxonomy.
CREATE TABLE public.m06_equipment_component_reference (
    reference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_class_id VARCHAR(32) NOT NULL
        REFERENCES public.equipment_class (equipment_class_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    equipment_class TEXT NOT NULL CHECK (btrim(equipment_class) <> ''),
    subsystem_assembly TEXT NOT NULL CHECK (btrim(subsystem_assembly) <> ''),
    subsystem_id_source_value TEXT NOT NULL CHECK (btrim(subsystem_id_source_value) <> ''),
    component_maintainable_item TEXT NOT NULL CHECK (btrim(component_maintainable_item) <> ''),
    taxonomy_code TEXT NOT NULL CHECK (btrim(taxonomy_code) <> ''),
    source_sheet TEXT NOT NULL,
    source_row_number INTEGER NOT NULL CHECK (source_row_number > 1),
    model_information_note TEXT NOT NULL,
    review_status TEXT NOT NULL DEFAULT 'PENDING_REVIEW'
        CHECK (btrim(review_status) <> ''),
    CONSTRAINT uq_m06_component_reference_source_row
        UNIQUE (source_sheet, source_row_number),
    CONSTRAINT uq_m06_component_reference_mapping
        UNIQUE (equipment_class_id, subsystem_assembly, component_maintainable_item, taxonomy_code)
);

CREATE INDEX ix_m06_component_reference_class
    ON public.m06_equipment_component_reference (equipment_class_id);

COMMENT ON TABLE public.m06_equipment_component_reference IS
    'Traceable source mapping from Group 1 Equipment_Reference; not an approved taxonomy or physical asset register.';
COMMENT ON COLUMN public.m06_equipment_component_reference.subsystem_id_source_value IS
    'Preserves the source text; the workbook says no subsystem ID is defined.';
COMMENT ON COLUMN public.m06_equipment_component_reference.review_status IS
    'PENDING_REVIEW is a conservative M06 implementation default, not a source approval field.';

-- Serialize parent-link edits so two concurrent hierarchy edits cannot race
-- past cycle detection. The lock is transaction-scoped.
CREATE FUNCTION public.m06_prevent_asset_hierarchy_cycle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $m06_cycle$
DECLARE
    would_cycle BOOLEAN;
BEGIN
    PERFORM pg_advisory_xact_lock(62006, 1);

    IF NEW.parent_asset_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF NEW.asset_id IS NOT NULL AND NEW.parent_asset_id = NEW.asset_id THEN
        RAISE EXCEPTION 'Asset hierarchy cycle rejected: a node cannot parent itself'
            USING ERRCODE = '23514';
    END IF;

    WITH RECURSIVE ancestor_chain(asset_id, parent_asset_id) AS (
        SELECT n.asset_id, n.parent_asset_id
        FROM public.asset_node AS n
        WHERE n.asset_id = NEW.parent_asset_id
        UNION
        SELECT p.asset_id, p.parent_asset_id
        FROM public.asset_node AS p
        JOIN ancestor_chain AS a ON p.asset_id = a.parent_asset_id
    )
    SELECT EXISTS (
        SELECT 1 FROM ancestor_chain WHERE asset_id = NEW.asset_id
    ) INTO would_cycle;

    IF would_cycle THEN
        RAISE EXCEPTION 'Asset hierarchy cycle rejected for asset_id %', NEW.asset_id
            USING ERRCODE = '23514';
    END IF;

    RETURN NEW;
END;
$m06_cycle$;

CREATE TRIGGER trg_m06_prevent_asset_hierarchy_cycle
BEFORE INSERT OR UPDATE OF parent_asset_id ON public.asset_node
FOR EACH ROW EXECUTE FUNCTION public.m06_prevent_asset_hierarchy_cycle();
