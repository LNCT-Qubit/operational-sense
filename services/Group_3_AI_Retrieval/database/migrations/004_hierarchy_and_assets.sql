-- 004_hierarchy_and_assets.sql
-- STATUS: DRAFT, pending Common Data Model v1.0
-- Reconciles M04 v1.2 (ASSET_NODE), M06 v2.0 (asset_node, cycle trigger, component
-- reference) and the project proposal (Organization, EquipmentModel).
--
-- Two separate hierarchies (M04 G1_Alignment_Review):
--   1. ASSET hierarchy (real plant assets): asset_node, parent -> child.
--   2. KNOWLEDGE taxonomy: equipment_class -> subsystem -> component -> failure mode
--      (class_subsystem, failure_mode_taxonomy). Synthetic cases are NOT assets.
--
-- Changes against M06's candidate migration (needs M06's agreement):
--   * equipment_class is created in 002 (not here), so M06's preflight guard would
--     fail. Do NOT run M06's 0001 migration together with this schema.
--   * asset_node gets organization_id (tenant, needed for RLS) and equipment_model_id.
--   * the cycle trigger also checks the parent belongs to the same organization.
--   * asset_level and status stay free text (Q01 open), as in M06.
--   * asset_id keeps M06's BIGINT identity (Q09 open).

BEGIN;

-- Which subsystems exist for which equipment class (knowledge taxonomy, not assets)
CREATE TABLE IF NOT EXISTS class_subsystem (
    equipment_class_id  TEXT   NOT NULL REFERENCES equipment_class (equipment_class_id) ON DELETE RESTRICT,
    subsystem_id        BIGINT NOT NULL REFERENCES subsystem (subsystem_id) ON DELETE RESTRICT,
    PRIMARY KEY (equipment_class_id, subsystem_id)
);

CREATE TABLE IF NOT EXISTS organization (
    organization_id  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name             TEXT NOT NULL UNIQUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS equipment_model (
    equipment_model_id  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    equipment_class_id  TEXT NOT NULL REFERENCES equipment_class (equipment_class_id) ON DELETE RESTRICT,
    model_designation   TEXT NOT NULL,                 -- as recorded, e.g. 'Kirloskar DB-100'
    is_illustrative     BOOLEAN NOT NULL DEFAULT TRUE, -- workbook: seed models are illustrative
    UNIQUE (equipment_class_id, model_designation)
);

-- Physical asset hierarchy (arbitrary depth, adjacency list), from M04/M06
CREATE TABLE IF NOT EXISTS asset_node (
    asset_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id        UUID NOT NULL REFERENCES organization (organization_id) ON DELETE RESTRICT,
    parent_asset_id        BIGINT,
    asset_level            TEXT NOT NULL CHECK (btrim(asset_level) <> ''),
    asset_name             TEXT NOT NULL CHECK (btrim(asset_name) <> ''),
    equipment_class_id     TEXT REFERENCES equipment_class (equipment_class_id) ON DELETE RESTRICT,
    equipment_model_id     UUID REFERENCES equipment_model (equipment_model_id) ON DELETE RESTRICT,
    model_label            TEXT,
    model_is_illustrative  BOOLEAN NOT NULL DEFAULT FALSE,
    site_identifier        TEXT,
    status                 TEXT NOT NULL DEFAULT 'PENDING_REVIEW' CHECK (btrim(status) <> ''),
    hierarchy_path         TEXT,                       -- display only, never used for authorization
    CONSTRAINT fk_asset_node_parent FOREIGN KEY (parent_asset_id)
        REFERENCES asset_node (asset_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_asset_node_not_self_parent CHECK (parent_asset_id IS NULL OR parent_asset_id <> asset_id)
);

CREATE INDEX IF NOT EXISTS ix_asset_node_parent ON asset_node (parent_asset_id);
CREATE INDEX IF NOT EXISTS ix_asset_node_class  ON asset_node (equipment_class_id);
CREATE INDEX IF NOT EXISTS ix_asset_node_org    ON asset_node (organization_id);
CREATE INDEX IF NOT EXISTS ix_asset_node_model  ON asset_node (equipment_model_id);

-- Source-provenance map from Group 1 Equipment_Reference (M06). Not an approved taxonomy.
CREATE TABLE IF NOT EXISTS m06_equipment_component_reference (
    reference_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_class_id          TEXT NOT NULL REFERENCES equipment_class (equipment_class_id) ON DELETE RESTRICT,
    equipment_class             TEXT NOT NULL CHECK (btrim(equipment_class) <> ''),
    subsystem_assembly          TEXT NOT NULL CHECK (btrim(subsystem_assembly) <> ''),
    subsystem_id_source_value   TEXT NOT NULL CHECK (btrim(subsystem_id_source_value) <> ''),
    component_maintainable_item TEXT NOT NULL CHECK (btrim(component_maintainable_item) <> ''),
    taxonomy_code               TEXT NOT NULL CHECK (btrim(taxonomy_code) <> ''),
    source_sheet                TEXT NOT NULL,
    source_row_number           INTEGER NOT NULL CHECK (source_row_number > 1),
    model_information_note      TEXT NOT NULL,
    review_status               TEXT NOT NULL DEFAULT 'PENDING_REVIEW' CHECK (btrim(review_status) <> ''),
    CONSTRAINT uq_m06_component_reference_source_row UNIQUE (source_sheet, source_row_number),
    CONSTRAINT uq_m06_component_reference_mapping
        UNIQUE (equipment_class_id, subsystem_assembly, component_maintainable_item, taxonomy_code)
);
CREATE INDEX IF NOT EXISTS ix_m06_component_reference_class ON m06_equipment_component_reference (equipment_class_id);

-- Cycle and cross-tenant protection for the asset hierarchy (adapted from M06)
CREATE OR REPLACE FUNCTION prevent_asset_hierarchy_cycle()
RETURNS TRIGGER LANGUAGE plpgsql AS $fn$
DECLARE
    would_cycle BOOLEAN;
    parent_org  UUID;
BEGIN
    PERFORM pg_advisory_xact_lock(62006, 1);   -- serialize parent edits

    IF NEW.parent_asset_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF NEW.asset_id IS NOT NULL AND NEW.parent_asset_id = NEW.asset_id THEN
        RAISE EXCEPTION 'Asset hierarchy cycle rejected: a node cannot parent itself' USING ERRCODE = '23514';
    END IF;

    SELECT organization_id INTO parent_org FROM asset_node WHERE asset_id = NEW.parent_asset_id;
    IF parent_org IS DISTINCT FROM NEW.organization_id THEN
        RAISE EXCEPTION 'Asset parent must belong to the same organization' USING ERRCODE = '23514';
    END IF;

    WITH RECURSIVE ancestor_chain(asset_id, parent_asset_id) AS (
        SELECT n.asset_id, n.parent_asset_id FROM asset_node n WHERE n.asset_id = NEW.parent_asset_id
        UNION
        SELECT p.asset_id, p.parent_asset_id FROM asset_node p JOIN ancestor_chain a ON p.asset_id = a.parent_asset_id
    )
    SELECT EXISTS (SELECT 1 FROM ancestor_chain WHERE asset_id = NEW.asset_id) INTO would_cycle;

    IF would_cycle THEN
        RAISE EXCEPTION 'Asset hierarchy cycle rejected for asset_id %', NEW.asset_id USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS trg_prevent_asset_hierarchy_cycle ON asset_node;
CREATE TRIGGER trg_prevent_asset_hierarchy_cycle
BEFORE INSERT OR UPDATE OF parent_asset_id ON asset_node
FOR EACH ROW EXECUTE FUNCTION prevent_asset_hierarchy_cycle();

CREATE INDEX IF NOT EXISTS idx_class_subsystem_sub ON class_subsystem (subsystem_id);
CREATE INDEX IF NOT EXISTS idx_model_class         ON equipment_model (equipment_class_id);

COMMIT;
