"""Generate database/sql/m09/m09_040_apply_curation.sql from the curation overlay (tools/curation.py).

The SQL is a pure diff between the raw SQL-import export and the curated export, so JSON and database stay in
sync. Run after the Step 4 imports and m09_010:  psql -f database/sql/m09/m09_040_apply_curation.sql
Idempotent (UPDATEs by natural key). Usage: python -m tools.build_curation_sql [--check]
"""
from __future__ import annotations

import argparse
import os
import sys

from tools import curation
from tools.export_synthetic_cases import build

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "database", "sql", "m09", "m09_040_apply_curation.sql")
DB = os.path.join(ROOT, "database")


def lit(v: str) -> str:
    return "'" + v.replace("'", "''") + "'"


def render() -> str:
    raw, cur = build(DB, curate=False), build(DB, curate=True)
    L = [
        "-- m09_040_apply_curation.sql  (GENERATED by tools/build_curation_sql.py from tools/curation.py; do not edit by hand)",
        f"-- Curation overlay {curation.CURATION_VERSION}: suggested measurement locations, pending-verification acceptance text,",
        "-- isolation warnings, Tier-3 linkage wording, safety_procedure labelling and one unambiguous subsystem mapping.",
        "-- Run AFTER the Step 4 imports and sql/m09/m09_010_resolve_subsystem_fk.sql. Idempotent. Nothing is deleted.",
        "-- No OEM limits, torques, clearances or thresholds are introduced; suggested locations are NOT OEM-verified.",
        "-- STATUS: executed on a scratch PostgreSQL 16.15 + pgvector 0.8.0 in the Group 3 Final build (see poc/execution_evidence/).",
        "BEGIN;", "",
    ]
    n_step = n_acc = 0
    for rc, cc in zip(raw["cases"], cur["cases"]):
        ref = cc["case_reference"]
        for rs, cs in zip(rc["troubleshooting_steps"], cc["troubleshooting_steps"]):
            sets = [f"{k} = {lit(cs[k])}" for k in ("check_measurement", "safety_warning") if cs[k] != rs[k]]
            if sets:
                L.append(f"UPDATE troubleshooting_step SET {', '.join(sets)} WHERE step_reference = {lit(cs['step_reference'])};")
                n_step += 1
        if cc["acceptance_criteria"] != rc["acceptance_criteria"]:
            L.append(f"UPDATE operational_case SET acceptance_criteria = {lit(cc['acceptance_criteria'])} WHERE case_reference = {lit(ref)};")
            n_acc += 1
    L.append("")
    for ref, r in sorted(curation.SUBSYSTEM_RESOLUTIONS.items()):
        L += [f"-- {ref}: {r['evidence']}",
              f"UPDATE operational_case SET subsystem_id = (SELECT subsystem_id FROM subsystem WHERE subsystem_name = {lit(r['subsystem_name'])})",
              f"WHERE case_reference = {lit(ref)} AND equipment_class_id = {lit(r['equipment_class_id'])} AND subsystem_source_label = {lit(r['source_label'])} AND subsystem_id IS NULL;",
              f"UPDATE historical_case h SET subsystem_id = c.subsystem_id FROM operational_case c WHERE h.case_id = c.case_id AND c.case_reference = {lit(ref)};", ""]
    L.append("-- General safety guidance rows: label as NOT approved plant procedures (wording only).")
    hz = ", ".join(lit(h) for h in curation.SAFETY_PROJECT_RULE_HAZARDS)
    L.append(f"UPDATE safety_procedure SET scope_type = scope_type || {lit(curation.SAFETY_SCOPE_SUFFIX)}")
    L.append(f"WHERE hazard NOT IN ({hz}) AND scope_type NOT LIKE '%NOT an approved plant procedure%';")
    L += ["", "COMMIT;", f"-- generated: {n_step} step updates, {n_acc} acceptance updates, {len(curation.SUBSYSTEM_RESOLUTIONS)} subsystem resolution(s)", ""]
    return "\n".join(L)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the committed file differs from a fresh render")
    a = ap.parse_args(argv)
    text = render()
    if a.check:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("m09_040 up to date" if ok else "m09_040 is STALE: run python -m tools.build_curation_sql")
        return 0 if ok else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(OUT, ROOT)); return 0


if __name__ == "__main__":
    sys.exit(main())
