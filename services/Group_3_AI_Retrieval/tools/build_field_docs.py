"""Generate case_schema/field_definitions.md from canonical_schema.json + the DB mapping (cannot drift)."""
import json, os
from integration import mapping
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def typ(d):
    t = d.get("type", "object" if "$ref" in d else "?")
    t = "/".join(t) if isinstance(t, list) else t
    if "enum" in d: t += " enum[" + ", ".join(str(x) for x in d["enum"] if x is not None) + "]"
    if "const" in d: t += f" const {d['const']!r}"
    if "$ref" in d: t = "object -> " + d["$ref"].split("/")[-1]
    if d.get("type") == "array": t = "array of " + typ(d["items"])
    return t.replace("|", "/")

def dest(name):
    if name in mapping.CASE_COLUMNS: return f"`operational_case.{name}`"
    if name in mapping.RESOLVED_FIELDS: return mapping.RESOLVED_FIELDS[name]
    return "**not stored**: " + mapping.UNSTORED_FIELDS[name]

def main():
    s = json.load(open(os.path.join(ROOT, "case_schema", "canonical_schema.json"), encoding="utf-8"))
    req = set(s["required"])
    L = ["# Field definitions: troubleshooting case schema v1.0.0", "",
         "> Generated by `python -m tools.build_field_docs` from `canonical_schema.json` and `integration/mapping.py`.",
         "> Field names are the approved database column names (migration 005). `additionalProperties` is false: unknown fields are rejected, not ignored.", "",
         "## Case (top level)", "", "| Field | Req. | Type | Meaning | Database destination |", "|---|---|---|---|---|"]
    for n, d in s["properties"].items():
        L.append(f"| `{n}` | {'**yes**' if n in req else 'no'} | {typ(d)} | {d.get('description','')} | {dest(n)} |")
    for name, d in s["$defs"].items():
        L += ["", f"## `{name}` object", "", "| Field | Req. | Type | Meaning |", "|---|---|---|---|"]
        r = set(d.get("required", []))
        for n, p in d["properties"].items():
            L.append(f"| `{n}` | {'**yes**' if n in r else 'no'} | {typ(p)} | {p.get('description','')} |")
    L += ["", "## Handling of missing / unknown information",
          "- Optional text fields may be `null` (unknown) or omitted. Never use placeholders such as `N/A`, `TBD`, `None typically`.",
          "- `subsystem_name`, `component_name`, `taxonomy_code` are `null` when unresolved. They are never guessed; each null is listed in `synthetic_dataset/unresolved_mappings.csv`.",
          "- `created_at`/`updated_at` are database-generated; exports keep them `null`.",
          "- `confirmed_cause` is `null` until a cause is confirmed; a suspected cause is never copied into it.", ""]
    open(os.path.join(ROOT, "case_schema", "field_definitions.md"), "w", encoding="utf-8", newline="\n").write("\n".join(L))
    print("ok")
main()
