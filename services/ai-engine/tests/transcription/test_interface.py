from __future__ import annotations

from pathlib import Path
from unittest.mock import MagicMock, patch

import pytest

from app.transcription.config import TranscriptionConfig
from app.transcription.models import TranscriptionStatus
import app.transcription.interface as iface


# ---------------------------------------------------------------------------
# Reset singleton before each test to prevent state leakage.
# ---------------------------------------------------------------------------


@pytest.fixture(autouse=True)
def reset_singleton() -> None:
    """Ensure a clean singleton state before and after every test."""
    iface.reset_service()
    yield
    iface.reset_service()


# ---------------------------------------------------------------------------
# Tests
# ---------------------------------------------------------------------------


class TestGetServiceSingleton:
    """Test 1: test_singleton_returns_same_instance"""

    def test_singleton_returns_same_instance(
        self, sample_config: TranscriptionConfig
    ) -> None:
        """Two calls to get_service() must return the identical object."""
        s1 = iface.get_service(config=sample_config)
        s2 = iface.get_service(config=sample_config)
        assert s1 is s2

    def test_singleton_ignores_config_on_second_call(
        self, sample_config: TranscriptionConfig
    ) -> None:
        """The config passed on the second call must be ignored (first-call wins)."""
        s1 = iface.get_service(config=sample_config)
        # Even with a different model name, the same instance should be returned.
        alt_config = TranscriptionConfig(model_name="base")
        s2 = iface.get_service(config=alt_config)
        assert s1 is s2


class TestResetService:
    """Test 2: test_reset_service_creates_new_instance"""

    def test_reset_service_creates_new_instance(
        self, sample_config: TranscriptionConfig
    ) -> None:
        """reset_service() must cause the next get_service() to create a new object."""
        s1 = iface.get_service(config=sample_config)
        iface.reset_service()
        s2 = iface.get_service(config=sample_config)
        # Must be a different instance.
        assert s1 is not s2


class TestTranscribeAudioConvenience:
    """Test 3: test_transcribe_audio_convenience_function"""

    def test_transcribe_audio_convenience_function(
        self,
        sample_config: TranscriptionConfig,
        valid_wav_file: Path,
    ) -> None:
        """transcribe_audio() must delegate to the service and return a result."""
        # Inject a mock provider so the real model is never loaded.
        mock_service = MagicMock()
        mock_result = MagicMock()
        mock_result.status = TranscriptionStatus.COMPLETED
        mock_service.transcribe.return_value = mock_result

        with patch.object(iface, "get_service", return_value=mock_service):
            result = iface.transcribe_audio(
                audio_path=str(valid_wav_file),
                recording_id="rec-test",
                config=sample_config,
            )

        assert result.status == TranscriptionStatus.COMPLETED
        mock_service.transcribe.assert_called_once()
        call_args = mock_service.transcribe.call_args
        req = call_args[0][0]  # positional first arg
        assert req.audio_path == str(valid_wav_file)
        assert req.recording_id == "rec-test"


class TestTranscriptionIdGeneration:
    """Test 4: test_transcription_id_generated_if_not_provided"""

    def test_transcription_id_generated_if_not_provided(
        self,
        sample_config: TranscriptionConfig,
        valid_wav_file: Path,
    ) -> None:
        """When transcription_id is None, the service must generate a UUID."""
        mock_service = MagicMock()
        mock_result = MagicMock()
        mock_result.transcription_id = "auto-generated-uuid"
        mock_result.status = TranscriptionStatus.COMPLETED
        mock_service.transcribe.return_value = mock_result

        with patch.object(iface, "get_service", return_value=mock_service):
            result = iface.transcribe_audio(
                audio_path=str(valid_wav_file),
                transcription_id=None,  # Must be auto-generated by service
                config=sample_config,
            )

        # Verify the request passed to service had transcription_id=None so
        # the service's UUID generation logic is exercised.
        call_args = mock_service.transcribe.call_args
        req = call_args[0][0]
        assert req.transcription_id is None  # Service will generate it internally
        # The result itself should carry a non-None id (mocked here).
        assert result.transcription_id is not None

