--

CREATE FUNCTION public.prevent_asset_hierarchy_cycle() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
    would_cycle BOOLEAN;
    parent_org  UUID;
BEGIN
    PERFORM pg_advisory_xact_lock(62006, 1);   -- serialize parent edits

    IF NEW.parent_asset_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF NEW.asset_id IS NOT NULL AND NEW.parent_asset_id = NEW.asset_id THEN
        RAISE EXCEPTION 'Asset hierarchy cycle rejected: a node cannot parent itself' USING ERRCODE = '23514';
    END IF;

    SELECT organization_id INTO parent_org FROM asset_node WHERE asset_id = NEW.parent_asset_id;
    IF parent_org IS DISTINCT FROM NEW.organization_id THEN
        RAISE EXCEPTION 'Asset parent must belong to the same organization' USING ERRCODE = '23514';
    END IF;

    WITH RECURSIVE ancestor_chain(asset_id, parent_asset_id) AS (
        SELECT n.asset_id, n.parent_asset_id FROM asset_node n WHERE n.asset_id = NEW.parent_asset_id
        UNION
        SELECT p.asset_id, p.parent_asset_id FROM asset_node p JOIN ancestor_chain a ON p.asset_id = a.parent_asset_id
    )
    SELECT EXISTS (SELECT 1 FROM ancestor_chain WHERE asset_id = NEW.asset_id) INTO would_cycle;

    IF would_cycle THEN
        RAISE EXCEPTION 'Asset hierarchy cycle rejected for asset_id %', NEW.asset_id USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;


