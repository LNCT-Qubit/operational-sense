-- 009_capture_pipeline.sql
-- US-07: Backend Integration and Data Persistence.
-- Apply AFTER 008_extraction_drafts.sql (US-06). Additive: no existing table is dropped,
-- no existing row is deleted. Rollback: database/rollback/009_capture_pipeline.down.sql
--
-- WHAT THIS ADDS
--   recording        one row per uploaded voice note + its processing status
--   transcription    one row per transcription ATTEMPT (US-05 TranscriptionResult)
--   extraction_draft (US-06, existing) gets real foreign keys to recording/transcription
--
-- LINK CHAIN (all tenant-safe: every FK carries organization_id)
--   recording 1 --- n transcription 1 --- 0..1 live extraction_draft
--
-- DESIGN NOTES
--   * Idempotency key = (organization_id, client_recording_id), the id the PWA generated at
--     capture time (US-03). Same principle as proposal Sec.4 / operational_case.client_capture_id.
--   * We deliberately do NOT write operational_case here. An extraction draft is not a case
--     (US-06 keeps them apart; operational_case needs a class + subsystem the 4-field
--     extraction does not carry).
--   * Status names are new (no server-side names existed). Failed states MUST carry a
--     failure_code and non-failed states MUST NOT (chk_recording_failure_code), so a failure
--     can never look like success and a retry must clear the old failure.
--   * RLS follows migration 007 exactly (ENABLE + FORCE, NULLIF(...,'') fails closed).

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. recording
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS recording (
    recording_id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id       UUID NOT NULL REFERENCES organization (organization_id) ON DELETE RESTRICT,
    client_recording_id   UUID NOT NULL,                  -- idempotency key generated by the PWA
    uploaded_by           TEXT NOT NULL,                  -- authenticated user id (JWT sub)
    mime_type             TEXT NOT NULL,                  -- normalized, no parameters, e.g. audio/wav
    size_bytes            BIGINT NOT NULL CHECK (size_bytes > 0),
    sha256                TEXT NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    storage_uri           TEXT NOT NULL,                  -- path relative to UPLOAD_DIR (never absolute)
    duration_ms           INTEGER CHECK (duration_ms IS NULL OR duration_ms >= 0),
    recorded_at           TIMESTAMPTZ,                    -- client capture time (may be hours before upload)
    processing_status     TEXT NOT NULL DEFAULT 'RECEIVED'
        CHECK (processing_status IN ('RECEIVED', 'TRANSCRIBING', 'TRANSCRIBED', 'TRANSCRIPTION_FAILED',
                                     'EXTRACTING', 'EXTRACTED', 'EXTRACTION_FAILED')),
    failure_code          TEXT,
    failure_message       TEXT,                           -- sanitized, safe to show to the client
    processing_started_at TIMESTAMPTZ,                    -- set while TRANSCRIBING/EXTRACTING (stale-claim recovery)
    transcription_attempts INTEGER NOT NULL DEFAULT 0 CHECK (transcription_attempts >= 0),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_recording_org_client UNIQUE (organization_id, client_recording_id),
    CONSTRAINT uq_recording_org_id     UNIQUE (organization_id, recording_id),   -- composite-FK target
    CONSTRAINT chk_recording_failure_code CHECK (
        (processing_status IN ('TRANSCRIPTION_FAILED', 'EXTRACTION_FAILED')) = (failure_code IS NOT NULL)),
    CONSTRAINT chk_recording_in_progress_has_start CHECK (
        processing_status NOT IN ('TRANSCRIBING', 'EXTRACTING') OR processing_started_at IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ix_recording_org_status_created
    ON recording (organization_id, processing_status, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_recording_org_user_created
    ON recording (organization_id, uploaded_by, created_at DESC);

-- ---------------------------------------------------------------------------
-- 2. transcription (one row per attempt; rows are immutable once written)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS transcription (
    transcription_id            UUID PRIMARY KEY,          -- generated by the backend, passed to US-05
    organization_id             UUID NOT NULL,
    recording_id                UUID NOT NULL,
    attempt_number              INTEGER NOT NULL CHECK (attempt_number >= 1),
    status                      TEXT NOT NULL CHECK (status IN ('COMPLETED', 'EMPTY', 'FAILED')),
    transcript                  TEXT,
    detected_language           TEXT,
    language_probability        NUMERIC(5, 4) CHECK (language_probability IS NULL OR language_probability BETWEEN 0 AND 1),
    segments                    JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(segments) = 'array'),
    processing_duration_seconds NUMERIC(10, 3) CHECK (processing_duration_seconds IS NULL OR processing_duration_seconds >= 0),
    error_code                  TEXT,
    error_message               TEXT,                      -- US-05 safe_message only
    model_name                  TEXT NOT NULL,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_transcription_recording FOREIGN KEY (organization_id, recording_id)
        REFERENCES recording (organization_id, recording_id) ON DELETE RESTRICT,
    CONSTRAINT uq_transcription_attempt UNIQUE (recording_id, attempt_number),
    -- composite-FK target so extraction_draft can prove draft -> transcription -> recording agree
    CONSTRAINT uq_transcription_org_rec_id UNIQUE (organization_id, recording_id, transcription_id),
    -- COMPLETED <=> there is real transcript text; never a "completed" blank
    CONSTRAINT chk_transcription_completed_has_text CHECK (
        (status = 'COMPLETED') = (transcript IS NOT NULL AND length(btrim(transcript)) > 0)),
    CONSTRAINT chk_transcription_failed_has_code CHECK ((status = 'FAILED') = (error_code IS NOT NULL))
);

-- At most one successful transcription per recording (a retry only happens after a non-success).
CREATE UNIQUE INDEX IF NOT EXISTS uq_transcription_one_completed
    ON transcription (recording_id) WHERE status = 'COMPLETED';

-- ---------------------------------------------------------------------------
-- 3. extraction_draft (US-06): real links to recording / transcription
-- ---------------------------------------------------------------------------
-- 3a. Preserve any legacy free-text transcription reference, then convert the column to UUID.
--     US-06 documented transcription_id as TEXT "until US-05 publishes its canonical contract".
ALTER TABLE extraction_draft ADD COLUMN IF NOT EXISTS legacy_transcription_ref TEXT;

DO $$
BEGIN
  IF (SELECT data_type FROM information_schema.columns
      WHERE table_schema = 'public' AND table_name = 'extraction_draft' AND column_name = 'transcription_id') = 'text' THEN

    UPDATE extraction_draft
       SET legacy_transcription_ref = transcription_id,
           transcription_id = NULL
     WHERE transcription_id IS NOT NULL;

    -- Fail loudly (and roll the whole migration back) rather than lose data if RLS hid rows
    -- from this session. Run migrations as the table owner/superuser, as migrate.sh does.
    IF EXISTS (SELECT 1 FROM extraction_draft WHERE transcription_id IS NOT NULL) THEN
      RAISE EXCEPTION '009: could not clear legacy transcription_id values (row-level security?). Run as owner/superuser.';
    END IF;

    ALTER TABLE extraction_draft ALTER COLUMN transcription_id TYPE UUID USING transcription_id::uuid;
  END IF;
END $$;

-- 3b. Direct link to the recording and tenant-safe composite foreign keys.
ALTER TABLE extraction_draft ADD COLUMN IF NOT EXISTS recording_id UUID;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_extraction_draft_recording') THEN
    ALTER TABLE extraction_draft ADD CONSTRAINT fk_extraction_draft_recording
      FOREIGN KEY (organization_id, recording_id)
      REFERENCES recording (organization_id, recording_id) ON DELETE RESTRICT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_extraction_draft_transcription') THEN
    -- Three columns: the draft's transcription must belong to the draft's recording AND organization.
    -- (MATCH SIMPLE: not enforced when recording_id or transcription_id is NULL.)
    ALTER TABLE extraction_draft ADD CONSTRAINT fk_extraction_draft_transcription
      FOREIGN KEY (organization_id, recording_id, transcription_id)
      REFERENCES transcription (organization_id, recording_id, transcription_id) ON DELETE RESTRICT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_extraction_draft_transcription_has_recording') THEN
    -- Without this, a draft could name a transcription but skip the recording, bypassing the FK above.
    ALTER TABLE extraction_draft ADD CONSTRAINT chk_extraction_draft_transcription_has_recording
      CHECK (transcription_id IS NULL OR recording_id IS NOT NULL);
  END IF;
END $$;

-- One live (non-rejected) draft per transcription: duplicate extraction cannot create duplicate drafts.
CREATE UNIQUE INDEX IF NOT EXISTS uq_extraction_draft_live_per_transcription
    ON extraction_draft (transcription_id)
    WHERE transcription_id IS NOT NULL AND status <> 'REJECTED';
CREATE INDEX IF NOT EXISTS ix_extraction_draft_recording
    ON extraction_draft (organization_id, recording_id) WHERE recording_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- 4. Row-Level Security (same pattern as 007) and grants for the application role
-- ---------------------------------------------------------------------------
ALTER TABLE recording     ENABLE ROW LEVEL SECURITY;
ALTER TABLE recording     FORCE  ROW LEVEL SECURITY;
ALTER TABLE transcription ENABLE ROW LEVEL SECURITY;
ALTER TABLE transcription FORCE  ROW LEVEL SECURITY;

DROP POLICY IF EXISTS tenant_select ON recording;
DROP POLICY IF EXISTS tenant_insert ON recording;
DROP POLICY IF EXISTS tenant_update ON recording;
DROP POLICY IF EXISTS tenant_select ON transcription;
DROP POLICY IF EXISTS tenant_insert ON transcription;

CREATE POLICY tenant_select ON recording FOR SELECT
  USING (organization_id = NULLIF(current_setting('app.current_org_id', true), '')::uuid);
CREATE POLICY tenant_insert ON recording FOR INSERT
  WITH CHECK (organization_id = NULLIF(current_setting('app.current_org_id', true), '')::uuid);
CREATE POLICY tenant_update ON recording FOR UPDATE
  USING (organization_id = NULLIF(current_setting('app.current_org_id', true), '')::uuid)
  WITH CHECK (organization_id = NULLIF(current_setting('app.current_org_id', true), '')::uuid);

-- transcription rows are append-only for the application role: SELECT + INSERT, no UPDATE policy/grant.
CREATE POLICY tenant_select ON transcription FOR SELECT
  USING (organization_id = NULLIF(current_setting('app.current_org_id', true), '')::uuid);
CREATE POLICY tenant_insert ON transcription FOR INSERT
  WITH CHECK (organization_id = NULLIF(current_setting('app.current_org_id', true), '')::uuid);

-- No DELETE grant anywhere (retirement is a status change, as in 007).
GRANT SELECT, INSERT, UPDATE ON recording     TO opsense_app;
GRANT SELECT, INSERT         ON transcription TO opsense_app;
-- extraction_draft grants (SELECT, INSERT, UPDATE) already exist from 008.

COMMIT;
